import AppKit
import Carbon
import ServiceManagement

/// Ties the watchers, the engine and the floating results together.
@MainActor
final class Core {
    static let shared = Core()
    let store = ResultStore()
    private var folder: FolderWatcher?
    private var clipTimer: DispatchSourceTimer?
    private var lastChange = NSPasteboard.general.changeCount
    static let marker = NSPasteboard.PasteboardType("pinch.optimisation.status")
    private static let transient: Set<String> = ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType", "com.apple.is-remote-clipboard"]

    // MARK: start

    func start() {
        FrontApp.shared.start()
        refreshFolder()
        let t = DispatchSource.makeTimerSource(queue: .main)
        t.schedule(deadline: .now() + 0.5, repeating: 0.5, leeway: .milliseconds(100))
        t.setEventHandler { MainActor.assumeIsolated { Core.shared.clipboardTick() } }
        t.resume()
        clipTimer = t
        let hk = HotKeys.shared
        _ = hk.registerCopyText(HotKeys.copyTextKey)
        hk.register(2, .init(keyCode: UInt32(kVK_ANSI_O), modifiers: UInt32(controlKey | shiftKey))) { Core.shared.optimiseClipboardNow(aggressive: false) }
        hk.register(3, .init(keyCode: UInt32(kVK_ANSI_A), modifiers: UInt32(controlKey | shiftKey))) { Core.shared.optimiseClipboardNow(aggressive: true) }
        hk.register(4, .init(keyCode: UInt32(kVK_ANSI_I), modifiers: UInt32(controlKey | shiftKey))) { Core.shared.optimiseClipboardNow(aggressive: false, preset: .ai) }
    }

    /// (Re)starts the watcher when the macOS screenshot folder changed or the setting was toggled.
    func refreshFolder() {
        let want = Prefs.watchOn ? Prefs.screenshotFolder : nil
        if folder?.dir == want { return }
        folder = nil
        if let want { folder = FolderWatcher(dir: want) { url, app in Core.shared.newFile(url, app: app) } }
    }

    static var launchAtLogin: Bool {
        get { SMAppService.mainApp.status == .enabled }
        set { if newValue { try? SMAppService.mainApp.register() } else { try? SMAppService.mainApp.unregister() } }
    }

    // MARK: files

    func newFile(_ original: URL, app: String) {
        guard !Prefs.paused, let kind = Kind.of(original), kind != .pdf else { return }
        var url = original
        if Prefs.autoName, AutoName.isScreenCapture(url) {
            url = AutoName.rename(url, app: app)
            folder?.ignore(url)
        }
        guard let backup = Backup.make(url) else { return }
        let item = Item(name: url.deletingPathExtension().lastPathComponent, ext: url.pathExtension, source: .file)
        item.dest = url; item.src = backup
        item.opts = .fromPrefs(blur: kind.isImage && kind != .gif)
        show(item)
        run(item, label: kind == .video ? "Optimising video" : "Optimising", manual: false)
    }

    func openImage(_ url: URL) {
        guard url.isFileURL, Kind.of(url)?.isImage == true else { return }
        guard !store.items.contains(where: { $0.running && $0.dest?.standardizedFileURL == url.standardizedFileURL }) else { return }
        let item = Item(name: url.deletingPathExtension().lastPathComponent, ext: url.pathExtension, source: .file)
        item.dest = url
        guard let backup = Backup.make(url) else {
            item.state = .failed("Could not back up this file")
            store.add(item); store.arm(item); KitSound.play(.error); return
        }
        item.src = backup
        item.opts = .fromPrefs(blur: Kind.of(url) != .gif)
        show(item); run(item, label: "Optimising")
    }

    // MARK: clipboard

    private func clipboardTick() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard Prefs.clipboardOn, !Prefs.paused else { return }
        handleClipboard(force: false)
    }

    func optimiseClipboardNow(aggressive: Bool, preset: Preset? = nil) { handleClipboard(force: true, aggressive: aggressive, preset: preset) }

    private func handleClipboard(force: Bool, aggressive: Bool = false, preset: Preset? = nil) {
        let pb = NSPasteboard.general
        guard let types = pb.types else { return }
        if !force, types.contains(Self.marker) || types.contains(where: { Self.transient.contains($0.rawValue) }) { return }
        let id = UUID().uuidString.prefix(8)
        let dir = Paths.clip.appendingPathComponent(String(id), isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], urls.count == 1,
           Kind.of(urls[0]) != nil, !urls[0].path.hasPrefix(Paths.root.path) || force {
            let file = urls[0], src = dir.appendingPathComponent(file.lastPathComponent)
            guard (try? FileManager.default.copyItem(at: file, to: src)) != nil else { return }
            let item = Item(name: file.deletingPathExtension().lastPathComponent, ext: file.pathExtension, source: .clipboard)
            item.src = src
            item.dest = dir.appendingPathComponent("out", isDirectory: true).appendingPathComponent(file.lastPathComponent)
            item.opts = .fromPrefs(preset: preset)
            item.opts.aggressive = aggressive
            show(item)
            run(item, label: Kind.of(file) == .video ? "Optimising video" : "Optimising", write: pb.changeCount, manual: force)
            return
        }
        guard let (data, ext) = Self.imageData(pb) else { return }
        let name = "Clipboard"
        let src = dir.appendingPathComponent("\(name).\(ext)")
        guard (try? data.write(to: src)) != nil else { return }
        let item = Item(name: name, ext: ext, source: .clipboard)
        item.src = src
        item.dest = dir.appendingPathComponent("out", isDirectory: true).appendingPathComponent("\(name).\(ext)")
        item.opts = .fromPrefs(preset: preset, blur: true)
        item.opts.aggressive = aggressive
        show(item)
        run(item, label: "Optimising", write: pb.changeCount, manual: force)
    }

    static func imageData(_ pb: NSPasteboard) -> (Data, String)? {
        if let d = pb.data(forType: .png) { return (d, "png") }
        if let d = pb.data(forType: NSPasteboard.PasteboardType("public.jpeg")) { return (d, "jpg") }
        if let d = pb.data(forType: .tiff), let png = NSBitmapImageRep(data: d)?.representation(using: .png, properties: [:]) { return (png, "png") }
        return nil
    }

    /// Write-back: file URL, image data, path string and the "already optimised" marker.
    private func writeClipboard(_ item: Item) {
        guard let url = item.dest else { return }
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.writeObjects([url as NSURL])
        if Kind.of(url)?.isImage == true, let d = try? Data(contentsOf: url) {
            pb.setData(d, forType: url.pathExtension.lowercased() == "png" ? .png : (url.pathExtension.lowercased() == "gif" ? NSPasteboard.PasteboardType("com.compuserve.gif") : NSPasteboard.PasteboardType("public.jpeg")))
            pb.setString(url.path, forType: .string)
        }
        pb.setString("true", forType: Self.marker)
        lastChange = pb.changeCount
    }

    // MARK: running

    func show(_ item: Item) {
        store.add(item)
        Task { @MainActor in
            if !item.opts.blur, let s = item.src ?? item.dest, let t = await Thumbs.make(s), item.running { item.thumb = t.v }
        }
    }

    /// Runs the engine from the untouched original into the destination.
    func run(_ item: Item, label: String, write expectChange: Int? = nil, manual: Bool = true) {
        guard let src = item.src, let dest = item.dest else { return }
        let job = Job()
        item.moment?.cancel(); item.pinch = nil
        item.oldBytes = fileSize(src)
        item.job = job
        item.state = .running(label)
        item.hideTask?.cancel()
        let opts = item.opts
        History.shared.begin(item)
        Task.detached {
            let result = Result { try Engine.process(input: src, output: dest, opts: opts, job: job) }
            await MainActor.run { Core.shared.finish(item, result, write: expectChange, manual: manual) }
        }
    }

    static func failedState(for error: Error) -> Item.State {
        switch error {
        case Failure.missingTool(let tool): .failed("Needs \(tool)")
        case Failure.other(let reason) where reason.contains("write"): .failed("Could not save this file")
        case Failure.tool: .failed("Could not optimise this file")
        default: .failed("Could not read this file")
        }
    }

    private func finish(_ item: Item, _ result: Result<Output, Error>, write expectChange: Int?, manual: Bool) {
        item.job = nil
        switch result {
        case let .success(o):
            item.oldBytes = o.oldBytes; item.newBytes = o.newBytes
            item.oldSize = o.oldSize; item.newSize = o.newSize
            item.hidden = o.hidden
            item.ssim = o.ssim
            if let u = o.url, u != item.dest { item.dest = u; item.ext = u.pathExtension; item.name = u.deletingPathExtension().lastPathComponent }
            item.state = .done
            History.shared.record(item)
            if item.source == .clipboard, expectChange == nil || expectChange == NSPasteboard.general.changeCount { writeClipboard(item) }
            Task { @MainActor in if let d = item.dest, let t = await Thumbs.make(d) { item.thumb = t.v } }
            if manual { KitSound.play(.confirm) }
            if o.newBytes < o.oldBytes && Prefs.floatingOn && !item.inRemoval {
                item.pinch = .step(0, from: o.oldBytes, to: o.newBytes)
                item.moment = Task { @MainActor in
                    do {
                        for index in 1...10 {
                            try await Task.sleep(for: .milliseconds(60))
                            item.pinch = .step(index, from: o.oldBytes, to: o.newBytes)
                            try await Task.sleep(for: .milliseconds(65))
                            item.pinch?.squeezed = false
                        }
                        item.pinch = nil
                    } catch {}
                }
            }
        case let .failure(e):
            History.shared.end(item)
            if case Failure.alreadyOptimised = e {
                item.oldBytes = item.src.map(fileSize) ?? 0; item.newBytes = item.oldBytes
                item.oldSize = item.src.flatMap(Engine.imageSize)
                item.state = .notice("Already optimised")
                if item.source == .file, let d = item.dest { XAttr.set(XAttr.status, "true", d) }
            } else if case Failure.cancelled = e {
                item.state = .notice("Stopped")
            } else {
                item.state = Self.failedState(for: e)
                if manual { KitSound.play(.error) }
            }
        }
        store.arm(item)
    }

    // MARK: item actions

    func restore(_ item: Item) {
        guard let src = item.src, let dest = item.dest, !item.running else { return }
        guard src.pathExtension.lowercased() == dest.pathExtension.lowercased() else { item.overlay = "The original is still next to it"; Task { @MainActor in try? await Task.sleep(for: .seconds(2)); item.overlay = nil }; return }
        let fm = FileManager.default
        let tmp = Paths.work.appendingPathComponent("\(UUID().uuidString).\(dest.pathExtension)")
        guard (try? fm.copyItem(at: src, to: tmp)) != nil else { return }
        if (try? fm.replaceItemAt(dest, withItemAt: tmp)) == nil { try? fm.moveItem(at: tmp, to: dest) }
        item.newBytes = item.oldBytes; item.hidden = 0
        item.opts = .fromPrefs()
        item.overlay = "Restored original"
        Task { @MainActor in if let thumb = await Thumbs.make(dest), !item.running { item.thumb = thumb.v } }
        if item.source == .clipboard { writeClipboard(item) }
        Task { @MainActor in try? await Task.sleep(for: .seconds(1.5)); item.overlay = nil }
    }
    func aggressive(_ item: Item) { item.opts.aggressive = true; item.opts.force = true; run(item, label: "Optimising harder") }
    func downscale(_ item: Item, _ f: Double) { item.opts.downscale = f; item.opts.force = true; run(item, label: "Downscaling") }
    func aiSize(_ item: Item) { setPreset(item, .ai) }
    func setPreset(_ item: Item, _ preset: Preset) {
        item.opts.preset = preset; item.opts.aggressive = false; item.opts.force = true
        item.opts.allowConvert = item.source == .file && item.opts.allowConvert
        run(item, label: preset == .ai ? "Resizing for AI" : "Optimising")
    }
    func convertGIF(_ item: Item) {
        guard let src = item.src ?? item.dest, let dir = item.dest?.deletingLastPathComponent(), Kind.of(src) == .gif else { return }
        Task.detached {
            let result = try? Engine.convertGIF(src, into: dir)
            await MainActor.run {
                guard let result, let url = result.url else { return Core.shared.notify("Could not convert this GIF") }
                let r = Item(name: url.deletingPathExtension().lastPathComponent, ext: "mp4", source: .file)
                r.dest = url; r.src = src; r.oldBytes = result.oldBytes; r.newBytes = result.newBytes; r.state = .done
                Core.shared.show(r); Core.shared.store.arm(r); KitSound.play(.confirm)
            }
        }
    }
    func showHidden(_ item: Item) { item.opts.blur = false; item.opts.force = true; run(item, label: "Showing") }
    func stop(_ item: Item) { item.job?.cancel() }

    func copyToClipboard(_ item: Item) {
        guard let url = item.dest else { return }
        let pb = NSPasteboard.general
        pb.clearContents(); pb.writeObjects([url as NSURL])
        if Kind.of(url)?.isImage == true, let img = NSImage(contentsOf: url) { pb.writeObjects([img]) }
        pb.setString("true", forType: Self.marker)
        lastChange = pb.changeCount
    }

    // MARK: copy text

    func copyText(from item: Item? = nil) {
        let pb = NSPasteboard.general
        var image: URL?
        if let item { image = item.dest }
        else if let (data, ext) = Self.imageData(pb) {
            let t = Paths.work.appendingPathComponent("\(UUID().uuidString).\(ext)")
            if (try? data.write(to: t)) != nil { image = t }
        } else { image = newestScreenshot() }
        guard let image else { return notify("No image to read") }
        let hide: BlurCategories = Prefs.blurOn ? Prefs.blurCategories : []
        Task.detached {
            let lines = Engine.decode(image).map { Redactor.text(of: $0, hide: hide).filter { !$0.isEmpty } } ?? []
            if image.path.hasPrefix(Paths.work.path) { try? FileManager.default.removeItem(at: image) }
            await MainActor.run {
                guard !lines.isEmpty else { return Core.shared.notify("No text found") }
                let pb = NSPasteboard.general
                pb.clearContents()
                pb.setString(lines.joined(separator: "\n"), forType: .string)
                pb.setString("true", forType: Core.marker)
                Core.shared.lastChange = pb.changeCount
                let r = Item(name: "Text", ext: "txt", source: .clipboard)
                r.textLines = lines.count; r.textPreview = lines[0]; r.state = .done
                Core.shared.store.add(r); Core.shared.store.arm(r)
            }
        }
    }

    private func newestScreenshot() -> URL? {
        let dir = Prefs.screenshotFolder
        let files = (try? FileManager.default.contentsOfDirectory(at: dir, includingPropertiesForKeys: [.creationDateKey])) ?? []
        return files.filter { [.png, .jpeg].contains(Kind.of($0)) }
            .max { ((try? $0.resourceValues(forKeys: [.creationDateKey]).creationDate) ?? .distantPast) < ((try? $1.resourceValues(forKeys: [.creationDateKey]).creationDate) ?? .distantPast) }
    }

    func notify(_ message: String) {
        let r = Item(name: message, ext: "", source: .clipboard)
        r.state = .notice(message)
        store.add(r); store.arm(r)
    }
}
